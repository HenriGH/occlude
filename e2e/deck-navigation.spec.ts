import { expect, test, type Page } from '@playwright/test'

async function createChild(page: Page, name: string) {
  await page.getByRole('button', { name: 'Ordner erstellen', exact: true }).click()
  await page.getByRole('textbox', { name: 'Name', exact: true }).fill(name)
  await page.getByRole('dialog').getByRole('button', { name: 'Ordner erstellen', exact: true }).click()
  await expect(page.getByRole('navigation', { name: 'Ordner', exact: true }).getByRole('button', { name, exact: true })).toHaveAttribute('aria-current', 'page')
}

test.beforeEach(async ({ context }) => {
  await context.route('**/*', route => ['127.0.0.1', 'localhost'].includes(new URL(route.request().url()).hostname) ? route.continue() : route.abort())
})

test('folder arrows collapse nested branches independently of selection and retain the view after reload', async ({ page }) => {
  await page.goto('/')
  await expect(page.getByRole('navigation', { name: 'Ordner', exact: true }).getByRole('button', { name: 'Mein Studium', exact: true })).toHaveAttribute('aria-current', 'page')
  await createChild(page, 'Anatomie')
  await createChild(page, 'Herz')
  const folders = page.getByRole('navigation', { name: 'Ordner', exact: true })
  await expect(folders.getByRole('button', { name: 'Herz', exact: true })).toHaveAttribute('aria-current', 'page')
  await expect(folders.getByRole('button', { name: /Herz (ein|aus)klappen/ })).toHaveCount(0)
  await folders.getByRole('button', { name: 'Anatomie einklappen' }).click()
  await expect(folders.getByRole('button', { name: 'Herz', exact: true })).toHaveCount(0)
  await expect(page.getByRole('heading', { name: 'Herz 0 Bilder', exact: true })).toBeVisible()
  const parent = folders.getByRole('button', { name: 'Mein Studium einklappen' })
  await parent.focus(); await page.keyboard.press('Space')
  await expect(folders.getByRole('button', { name: 'Anatomie', exact: true })).toHaveCount(0)
  await expect(page.getByRole('heading', { name: 'Herz 0 Bilder', exact: true })).toBeVisible()
  await page.reload()
  await expect(folders.getByRole('button', { name: 'Mein Studium ausklappen' })).toHaveAttribute('aria-expanded', 'false')
  await folders.getByRole('button', { name: 'Mein Studium ausklappen' }).press('Enter')
  await expect(folders.getByRole('button', { name: 'Anatomie ausklappen' })).toHaveAttribute('aria-expanded', 'false')
  await expect(folders.getByRole('button', { name: 'Herz', exact: true })).toHaveCount(0)
  await folders.getByRole('button', { name: 'Anatomie ausklappen' }).click()
  await expect(folders.getByRole('button', { name: 'Herz', exact: true })).toHaveAttribute('aria-current', 'page')
  await folders.getByRole('button', { name: 'Mein Studium', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Anatomie', exact: true })).toBeVisible()
  await expect(folders.getByRole('button', { name: 'Herz', exact: true })).toBeVisible()
  await page.screenshot({ path: 'test-results/deck-navigation-desktop.png', fullPage: true })
})

test('mobile toggles keep the menu open and selecting a hidden child from the dashboard reveals its ancestry', async ({ page }) => {
  await page.goto('/')
  await expect(page.getByRole('navigation', { name: 'Ordner', exact: true }).getByRole('button', { name: 'Mein Studium', exact: true })).toHaveAttribute('aria-current', 'page')
  await createChild(page, 'Anatomie')
  await createChild(page, 'Herz')
  await page.setViewportSize({ width: 390, height: 844 })
  const folders = page.getByRole('navigation', { name: 'Ordner', exact: true })
  const menu = page.getByRole('button', { name: 'Menü öffnen' })
  await menu.click()
  await folders.getByRole('button', { name: 'Mein Studium', exact: true }).click()
  await expect(menu).toHaveAttribute('aria-expanded', 'false')
  await menu.click()
  await folders.getByRole('button', { name: 'Anatomie einklappen' }).click()
  await folders.getByRole('button', { name: 'Mein Studium einklappen' }).click()
  await expect(menu).toHaveAttribute('aria-expanded', 'true')
  await expect(folders.getByRole('button', { name: 'Anatomie', exact: true })).toHaveCount(0)
  // Close the drawer without changing the current folder.
  await page.locator('.sidebar-scrim').click({ position: { x: 370, y: 400 } })
  await page.getByRole('button', { name: /^Anatomie .*Leer/ }).click()
  await page.getByRole('button', { name: /^Herz .*Leer/ }).click()
  await menu.click()
  await expect(folders.getByRole('button', { name: 'Mein Studium einklappen' })).toHaveAttribute('aria-expanded', 'true')
  await expect(folders.getByRole('button', { name: 'Anatomie einklappen' })).toHaveAttribute('aria-expanded', 'true')
  await expect(folders.getByRole('button', { name: 'Herz', exact: true })).toHaveAttribute('aria-current', 'page')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: 'test-results/deck-navigation-mobile.png', fullPage: true, animations: 'disabled' })
})
