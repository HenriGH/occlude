import { expect, test } from '@playwright/test'
import { cloudFixture, draw, localState, seedWorkspace } from './helpers/cloud'

test('mobile refresh, editing and review stay local while expired-session recovery stalls or fails', async ({ page, context }) => {
  const fixture = await cloudFixture(page)
  try {
    fixture.cloud.snapshot = await seedWorkspace(page, true)
    fixture.cloud.holdAuth = true
    await page.setViewportSize({ width: 390, height: 844 })
    await page.reload()
    await expect(page.getByRole('heading', { name: 'Übersicht' })).toBeVisible({ timeout: 2000 })
    await expect.poll(() => fixture.cloud.authRequests).toBeGreaterThan(0)
    expect(fixture.cloud.pulls).toBe(0)
    await page.getByRole('button', { name: 'Bild mit 2 Karten bearbeiten' }).click()
    await expect(page.getByRole('heading', { name: 'Masken bearbeiten' })).toBeVisible({ timeout: 1500 })
    await draw(page, .7)
    await page.getByRole('button', { name: '3 Karten speichern' }).click()
    await expect(page.getByRole('heading', { name: 'Bibliothek' })).toBeVisible({ timeout: 1500 })
    await page.getByRole('button', { name: 'Lernen', exact: true }).click()
    await page.getByRole('button', { name: 'Antwort zeigen' }).click()
    await page.getByRole('button', { name: /^Gut/ }).click()
    expect(await localState(page)).toEqual({ cards: 3, reviews: 1, pending: 2, locked: false })
    fixture.authGate.resolve()
    await expect.poll(() => page.evaluate(() => Object.keys(localStorage).some(k => k.endsWith('-auth-token')))).toBe(false)
    await expect(page.getByRole('button', { name: 'Antwort zeigen' })).toBeVisible()
    await page.reload()
    await expect(page.getByRole('heading', { name: 'Übersicht' })).toBeVisible({ timeout: 2000 })
    expect(await localState(page)).toEqual({ cards: 3, reviews: 1, pending: 2, locked: false })
    await context.setOffline(true)
    await page.getByRole('button', { name: 'Bild mit 3 Karten bearbeiten' }).click()
    await expect(page.getByRole('heading', { name: 'Masken bearbeiten' })).toBeVisible()
    expect(fixture.cloud.uploads).toBe(0)
  } finally { fixture.release() }
})

test('stalled pulls and pushes do not block edits/reviews; new work drains in the background without reuploading cached images', async ({ page }) => {
  await page.setViewportSize({ width: 1280, height: 1000 })
  const fixture = await cloudFixture(page)
  try {
    fixture.cloud.snapshot = await seedWorkspace(page, false)
    fixture.cloud.holdSnapshot = true; fixture.cloud.holdApply = true
    await page.reload()
    await expect(page.getByRole('heading', { name: 'Übersicht' })).toBeVisible({ timeout: 2000 })
    await expect.poll(() => fixture.cloud.pulls).toBeGreaterThan(0)
    await page.getByRole('button', { name: 'Bild mit 2 Karten bearbeiten' }).click()
    await draw(page, .7)
    await page.getByRole('button', { name: '3 Karten speichern' }).click()
    await expect(page.getByRole('heading', { name: 'Bibliothek' })).toBeVisible({ timeout: 1500 })
    expect((await localState(page)).pending).toBe(1)
    fixture.snapshotGate.resolve()
    await expect.poll(() => fixture.cloud.operations.length).toBe(1)
    await page.getByRole('button', { name: 'Bild mit 3 Karten bearbeiten' }).click()
    await draw(page, .85)
    await page.getByRole('button', { name: '4 Karten speichern' }).click()
    await expect(page.getByRole('heading', { name: 'Bibliothek' })).toBeVisible({ timeout: 1500 })
    await page.getByRole('button', { name: 'Lernen', exact: true }).click()
    await page.getByRole('button', { name: 'Antwort zeigen' }).click()
    await page.getByRole('button', { name: /^Gut/ }).click()
    expect(await localState(page)).toEqual({ cards: 4, reviews: 1, pending: 3, locked: false })
    fixture.applyGate.resolve()
    await expect.poll(async () => (await localState(page)).pending, { timeout: 5000 }).toBe(0)
    expect(fixture.cloud.operations.map(op => op.kind)).toEqual(['image.put', 'image.put', 'review.add'])
    expect(fixture.cloud.uploads).toBe(0)
    expect(fixture.cloud.verifications).toBe(1)
    expect(fixture.cloud.snapshot.cards).toHaveLength(4)
    expect(fixture.cloud.snapshot.reviews).toHaveLength(1)
    await page.reload()
    await expect(page.getByRole('heading', { name: 'Übersicht' })).toBeVisible({ timeout: 2000 })
    expect(await localState(page)).toEqual({ cards: 4, reviews: 1, pending: 0, locked: false })
  } finally { fixture.release() }
})
